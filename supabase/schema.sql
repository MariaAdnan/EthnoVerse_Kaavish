-- EthnoVerse database schema
--
-- Creates the tables, keys and storage buckets the website, admin tools and 3D
-- worker expect, so a new Supabase project can be set up from scratch. Run it
-- once in the Supabase SQL Editor, then run rls_policies.sql.
--
-- Reconstructed on 2026-10-10 from the live rows readable with the public key,
-- the columns the code reads and writes (website/src/services, the 3D tour and
-- website/pipeline.py) and rls_policies.sql. For an exact copy of the live
-- database, a project owner can run:
--   supabase db dump --schema public --file supabase/schema.live.sql

begin;

create extension if not exists pgcrypto;

create table if not exists public.communities (
  community_id uuid primary key default gen_random_uuid(),
  name text not null,
  location text,
  short_description text,
  long_description text,
  language text,
  contact_info text,
  picture_cloudinary_url text,
  tour_url text,
  -- desert | grass | rocky | mountains | custom (custom uses terrain-files/<id>-terrain.glb)
  terrain_type text,
  -- {scale, rotX, rotY, rotZ, posX, posY, posZ}; the tour also accepts it as a JSON string
  terrain_transform jsonb,
  custom_glb_transform jsonb,
  created_at timestamp default now()
);

create table if not exists public.interviews (
  id bigint generated by default as identity primary key,
  community_id uuid not null references public.communities (community_id) on delete cascade,
  title text not null,
  audio_cloudinary_url text not null,
  picture_cloudinary_url text,
  interviewer text,
  interviewee text,
  interview_notes_by text,
  date date,
  summary_text text,
  summary_urdu text,
  summary_sindhi text,
  summary_html jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.visual_media (
  id bigint generated by default as identity primary key,
  community_id uuid not null references public.communities (community_id) on delete cascade,
  title text,
  description text,
  picture_cloudinary_url text not null,
  -- JSON array of lowercase tags, e.g. ["tattoo", "temple"]; search uses @> on it
  tags jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.documents (
  id bigint generated by default as identity primary key,
  community_id uuid not null references public.communities (community_id) on delete cascade,
  title text not null,
  description text,
  author text,
  pdf_cloudinary_url text not null,
  pages integer,
  file_size_kb integer,
  created_at timestamptz not null default now()
);

create table if not exists public.tour_objects (
  id uuid primary key default gen_random_uuid(),
  community_id uuid not null references public.communities (community_id) on delete cascade,
  object_name text not null,
  object_url text not null,
  -- 'ply' for Gaussian-splat scans; anything else is loaded as a GLB model
  type text not null default 'ply',
  position_x double precision not null default 0,
  position_y double precision not null default 0,
  position_z double precision not null default 0,
  rotation_x double precision not null default 0,
  rotation_y double precision not null default 0,
  rotation_z double precision not null default 0,
  offset_x double precision not null default 0,
  offset_y double precision not null default 0,
  offset_z double precision not null default 0,
  scale double precision not null default 1,
  label_title text,
  label_description text,
  created_at timestamptz not null default now()
);

create table if not exists public.model_jobs (
  id uuid primary key default gen_random_uuid(),
  community_id uuid references public.communities (community_id) on delete set null,
  media_id uuid,
  object_name text not null,
  images_zip_url text,
  video_url text,
  status text not null default 'queued'
    check (status in ('queued', 'processing', 'done', 'failed')),
  progress integer not null default 0 check (progress between 0 and 100),
  message text,
  model_url text,
  created_at timestamptz not null default now()
);

-- One row per provisioned administrator (see docs/ADMIN_OPERATIONS.md).
create table if not exists public.users (
  user_id uuid primary key references auth.users (id) on delete cascade,
  role text not null default 'viewer',
  created_at timestamptz not null default now()
);

create index if not exists interviews_community_id_idx on public.interviews (community_id);
create index if not exists visual_media_community_id_idx on public.visual_media (community_id);
create index if not exists documents_community_id_idx on public.documents (community_id);
create index if not exists tour_objects_community_id_idx on public.tour_objects (community_id);
create index if not exists model_jobs_status_idx on public.model_jobs (status);

-- Public buckets read by the 3D tour; writes are limited to admins by rls_policies.sql.
insert into storage.buckets (id, name, public)
values
  ('terrain-files', 'terrain-files', true),
  ('tour-objects', 'tour-objects', true)
on conflict (id) do nothing;

commit;
